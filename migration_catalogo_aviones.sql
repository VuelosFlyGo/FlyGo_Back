CREATE TABLE IF NOT EXISTS aviones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    modelo VARCHAR(80) NOT NULL UNIQUE,
    asientos_ejecutiva INTEGER NOT NULL CHECK (asientos_ejecutiva > 0 AND asientos_ejecutiva % 4 = 0),
    asientos_turista INTEGER NOT NULL CHECK (asientos_turista > 0 AND asientos_turista % 4 = 0)
);

